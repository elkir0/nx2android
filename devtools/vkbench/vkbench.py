#!/usr/bin/env python3
"""vkbench: a CPU benchmark of the Android replay's per-draw path on the Mac (devtools/vkbench).

The Vulkan backend's own sources (nxnative/dm/android/gfx_vk_{core,exec,tex,shader,dq}.c) are built for the host with a fake driver
(fake_vk.c: the phone's Adreno 840 as run 13 reports it, every call recorded and costed apart), the host's stand-ins (host_stubs.c, with
hle_nvn.c's own virtual pool translation cut into vkb_vpool.inc) and a game (bench.c: a race frame of Mario Kart World 1.8.0, built from the
port's shader bundle and the counts the Mac and the phone logged). It prints the replay's per-frame line as the phone logs it.

  vkbench.py build [--src DIR] [--out DIR] [--cflags "..."] [--label NAME]     build a variant (sources from DIR: a scratch copy with patches applied)
  vkbench.py run --out DIR [--frames N] [--env K=V ...] [--json FILE] [--profile SECONDS]
  vkbench.py ab --a DIR --b DIR [--runs N] [--env K=V ...]                       interleaved runs of two builds, medians

Needs: the NDK (Vulkan headers, glslc), a port's shader bundle and its profile's shader_pairs.tsv (VKB_BUNDLE / VKB_PAIRS, or --bundle / --pairs).
"""
import argparse, json, os, shutil, statistics, subprocess, sys, tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
DM = REPO / 'nxnative/dm'
NDK_DEFAULT = os.environ.get('ANDROID_NDK_HOME') or str(Path.home() / 'Library/Application Support/nx2android/toolchains/android-ndk-r27c')
GAME = '0400C3F00006E000'   # (the profile whose header the backend is built with: the bench needs a game profile header, any game's would do)
SRCS = ['gfx_vk_core.c', 'gfx_vk_exec.c', 'gfx_vk_tex.c', 'gfx_vk_shader.c', 'gfx_vk_dq.c']


def region(src, start, end):
    a = src.index(start)
    return src[a:src.index(end, a)]


def vpool_inc(out):
    """hle_nvn.c's virtual pool tables, page table lookup and Android translation (nvn_virt_xlat), as tests/test_vk_vpool.py cuts them."""
    s = (DM / 'gfx/nvn/hle_nvn.c').read_text(encoding='utf-8')
    body = region(s, 'enum { NVRUN = 1024, VPT_LEAF = 512 };', 'static struct vpool *vpool_of')
    body += region(s, 'static const vpte *vpt_get(', '\nstatic void vpt_set(') + '\n'
    body += region(s, '// ---- aliased virtual pools on Android', '// ---- end of aliased virtual pools ----')
    (out / 'vkb_vpool.inc').write_text('// generated by devtools/vkbench/vkbench.py from nxnative/dm/gfx/nvn/hle_nvn.c: do not edit\n' + body, encoding='utf-8')


def gen_headers(out, ndk, games_dir):
    """The game profile and Android headers and the backend's embedded SPIR-V, as build.py makes them."""
    gen = out / 'gen'; gen.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ)
    if games_dir: env['DM_GAMES_DIR'] = games_dir
    py = sys.executable
    subprocess.run([py, str(DM / 'games/game.py'), 'header', GAME, str(gen / 'game_profile.h')], check=True, env=env, capture_output=True)
    subprocess.run([py, str(DM / 'android/tools/android_profile.py'), 'header', GAME, str(gen / 'android_profile.h')], check=True, env=env, capture_output=True)
    host = 'darwin-x86_64'
    glslc = Path(ndk) / 'shader-tools' / host / 'glslc'
    import struct
    for sh in sorted((DM / 'android/shaders').glob('*.*')):
        hdr = gen / f'{sh.stem}_{sh.suffix[1:]}.spv.h'
        if hdr.exists() and hdr.stat().st_mtime >= sh.stat().st_mtime: continue
        spv = gen / f'{sh.name}.spv'
        subprocess.run([str(glslc), '--target-env=vulkan1.1', '-O', str(sh), '-o', str(spv)], check=True)
        w = spv.read_bytes(); n = len(w) // 4
        hdr.write_text(f'static const uint32_t {sh.stem}_{sh.suffix[1:]}_spv[] = {{{", ".join(f"{x:#010x}" for x in struct.unpack(f"<{n}I", w))}}};\n')
    # the NDK's Vulkan headers (vulkan.h with vulkan_android.h, vk_video), linked rather than copied
    inc = out / 'vkinc'; inc.mkdir(exist_ok=True)
    sysinc = Path(ndk) / 'toolchains/llvm/prebuilt' / host / 'sysroot/usr/include'
    for d in ('vulkan', 'vk_video'):
        link = inc / d
        if link.is_symlink() or link.exists(): link.unlink()
        link.symlink_to(sysinc / d)
    return gen, inc


def build(a):
    out = Path(a.out).resolve(); out.mkdir(parents=True, exist_ok=True); obj = out / 'obj'; obj.mkdir(exist_ok=True)
    src = Path(a.src).resolve() if a.src else DM / 'android'
    gen, vkinc = gen_headers(out, a.ndk, a.games_dir)
    vpool_inc(out)
    cc = os.environ.get('CC', 'clang')
    # the variant's own sources first: a scratch copy may carry patched headers too (gfx_vk.h, nvn_hmap.h)
    common = ['-std=gnu11', '-D_GNU_SOURCE', '-DDM_ANDROID=1', '-fno-strict-aliasing', '-g', '-Wno-everything', f'-I{src}', f'-I{HERE / "shim"}', f'-I{vkinc}',
              f'-I{DM / "host"}', f'-I{DM / "gfx/nvn"}', f'-I{DM / "gfx/tex"}', f'-I{DM / "gfx/nvn/include"}', f'-I{gen}', f'-I{DM / "android"}', f'-I{out}']
    opt = (a.cflags or '-O2 -fno-omit-frame-pointer').split()
    jobs = []
    for f in SRCS: jobs.append((src / f, ['-include', str(HERE / 'shim/vkbench_force.h')]))
    for f in (DM / 'gfx/nvn/nvn_tex.c', DM / 'gfx/tex/nvn_deswizzle.c'): jobs.append((f, ['-include', str(HERE / 'shim/vkbench_force.h')]))
    for f in ('fake_vk.c', 'host_stubs.c', 'bench.c'): jobs.append((HERE / f, []))
    objs = []
    procs = []
    for s, extra in jobs:
        o = obj / (s.stem + '.o'); objs.append(o)
        procs.append((s, subprocess.Popen([cc] + common + opt + extra + ['-c', str(s), '-o', str(o)], stderr=subprocess.PIPE, text=True)))
    bad = 0
    for s, p in procs:
        err = p.communicate()[1]
        if p.returncode: bad = 1; print(f'--- {s}\n{err}', file=sys.stderr)
    if bad: sys.exit(1)
    lflags = [x for x in opt if x.startswith('-flto') or x.startswith('-fuse-ld')]
    r = subprocess.run([cc] + lflags + [str(o) for o in objs] + ['-o', str(out / 'vkbench'), '-lpthread', '-lm'], capture_output=True, text=True)
    if r.returncode: print(r.stderr, file=sys.stderr); sys.exit(1)
    (out / 'build.json').write_text(json.dumps({'src': str(src), 'cflags': opt, 'label': a.label or ''}, indent=1))
    print(f'built {out / "vkbench"} ({a.label or src})')


def run_env(a, out):
    env = dict(os.environ)
    env.setdefault('VKB_BUNDLE', a.bundle); env.setdefault('VKB_PAIRS', a.pairs)
    env.setdefault('DM_VK_MT_REPLAY', '1')   # as the phone runs (env.txt)
    root = out / 'root'; root.mkdir(exist_ok=True); env['DM_ROOT'] = str(root)
    env['VKB_LOG'] = str(out / 'log.txt')
    env['VKB_FRAMES'] = str(a.frames)
    for kv in a.env or []: k, v = kv.split('=', 1); env[k] = v
    return env


def run(a):
    out = Path(a.out).resolve(); env = run_env(a, out)
    if a.json: env['VKB_JSON'] = a.json
    env.setdefault('VKB_LABEL', json.loads((out / 'build.json').read_text()).get('label', ''))
    p = subprocess.Popen([str(out / 'vkbench')], env=env, stdout=subprocess.PIPE, text=True)
    if a.profile:
        import time; time.sleep(a.profile_delay)
        prof = out / 'sample.txt'
        subprocess.run(['sample', str(p.pid), str(a.profile), '-file', str(prof)], capture_output=True)
        print(f'profile: {prof}')
    txt = p.communicate()[0]; print(txt, end='')
    if p.returncode: sys.exit(p.returncode)


def ab(a):
    """Interleaved runs of two builds (A B A B ...): the medians of each, so drift (heat, other work on the machine) falls on both."""
    res = {'a': [], 'b': []}
    with tempfile.TemporaryDirectory() as td:
        for i in range(a.runs):
            for k in ('a', 'b'):
                out = Path(getattr(a, k)).resolve(); env = run_env(a, out); js = Path(td) / f'{k}.json'; env['VKB_JSON'] = str(js); env['VKB_LABEL'] = k
                r = subprocess.run([str(out / 'vkbench')], env=env, capture_output=True, text=True)
                if r.returncode: print(r.stdout, r.stderr, file=sys.stderr); sys.exit(1)
                res[k].append(json.loads(js.read_text().strip().splitlines()[-1])); js.unlink()
    keys = ['minstr', 'mcycles', 'cpu_p10', 'cpu_p50', 'replay_ms', 'desc_ms', 'collect_ms', 'hash_ms', 'new_ms', 'pipe_ms', 'wall_avg', 'draws', 'reused', 'new', 'memo', 'sets', 'updates', 'desc_writes', 'binds', 'pushes', 'calls']
    print(f'{"metric":12} {"A (" + Path(a.a).name + ")":>22} {"B (" + Path(a.b).name + ")":>22} {"B/A":>7}')
    for k in keys:
        x = statistics.median(r[k] for r in res['a']); y = statistics.median(r[k] for r in res['b'])
        print(f'{k:12} {x:22.3f} {y:22.3f} {y / x if x else float("nan"):7.3f}')
    if a.json:
        with open(a.json, 'a') as f: f.write(json.dumps({'a': str(a.a), 'b': str(a.b), 'runs': a.runs, 'env': a.env or [], 'A': res['a'], 'B': res['b']}) + '\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = ap.add_subparsers(dest='cmd', required=True)
    b = sp.add_parser('build'); b.add_argument('--src'); b.add_argument('--out', required=True); b.add_argument('--cflags'); b.add_argument('--label'); b.add_argument('--ndk', default=NDK_DEFAULT)
    b.add_argument('--games-dir', default=os.environ.get('DM_GAMES_DIR'))
    for name in ('run', 'ab'):
        r = sp.add_parser(name); r.add_argument('--frames', type=int, default=300); r.add_argument('--env', action='append'); r.add_argument('--json')
        r.add_argument('--bundle', default=os.environ.get('VKB_BUNDLE', str(REPO / '.gamedump/MarioKartWorld/MarioKartWorld-data/shaders.dmsv')))
        r.add_argument('--pairs', default=os.environ.get('VKB_PAIRS', str(REPO / '.gamedump/MarioKartWorld/0400C3F00006E000_build/profile-derived/0400C3F00006E000/shader_pairs.tsv')))
        if name == 'run': r.add_argument('--out', required=True); r.add_argument('--profile', type=int); r.add_argument('--profile-delay', type=float, default=3.0)
        else: r.add_argument('--a', required=True); r.add_argument('--b', required=True); r.add_argument('--runs', type=int, default=5)
    a = ap.parse_args()
    {'build': build, 'run': run, 'ab': ab}[a.cmd](a)


if __name__ == '__main__':
    main()
